/**
 * KATA Framework - Type Facade: tenant resources (branches, terminals, CSV imports)
 *
 * Wire shapes of `/tenants/{tenantId}/branches` and `/tenants/{tenantId}/terminals`
 * (SUC cases). Field names are PascalCase as the backend sends them (ADR-0018 notes).
 * Hand-written facades: the OpenAPI document does not describe the encrypted envelope.
 *
 * Usage:
 *   import type { BranchData, CreateBranchPayload } from '@schemas/resources.types';
 */

/** Branch (sede) as the backend returns it. `TerminalsCount` counts the branch's non-deleted terminals. */
export interface BranchData {
  Id: number
  TenantId: number
  BranchCode: string
  BranchName: string
  Address?: string | null
  Department?: string | null
  IsActive: boolean
  CreatedAt: string
  CreatedBy: string
  UpdatedAt?: string | null
  UpdatedBy?: string | null
  TenantName?: string | null
  TerminalsCount: number
}

/** `POST /tenants/{tenantId}/branches`: the tenant comes from the route, the creator from the session. */
export interface CreateBranchPayload {
  BranchCode: string
  BranchName: string
  Address?: string | null
  Department?: string | null
}

/** `PUT /tenants/{tenantId}/branches/{id}`: every field optional (a partial update is valid). The code cannot change. */
export interface UpdateBranchPayload {
  BranchName?: string
  Address?: string | null
  Department?: string | null
  IsActive?: boolean
}

/** Terminal as the backend returns it. `DevicesCount` counts the terminal's non-deleted devices. */
export interface TerminalData {
  Id: number
  TenantId: number
  BranchId: number
  TerminalName: string
  HostName?: string | null
  Description?: string | null
  Mac?: string | null
  IpAddress?: string | null
  DeviceType?: string | null
  Imei?: string | null
  IsActive: boolean
  CreatedAt: string
  CreatedBy: string
  UpdatedAt?: string | null
  UpdatedBy?: string | null
  TenantName?: string | null
  BranchName?: string | null
  DevicesCount: number
}

/** `POST /tenants/{tenantId}/terminals`: a terminal needs its branch, a name, a MAC and a device type (MOVIL also needs the IMEI). */
export interface CreateTerminalPayload {
  BranchId: number
  TerminalName: string
  HostName?: string | null
  Description?: string | null
  Mac: string
  IpAddress?: string | null
  DeviceType?: string | null
  Imei?: string | null
}

/** `PUT /tenants/{tenantId}/terminals/{id}`: every field optional (a partial update is valid). */
export interface UpdateTerminalPayload {
  BranchId?: number
  TerminalName?: string
  HostName?: string | null
  Description?: string | null
  Mac?: string
  IpAddress?: string | null
  DeviceType?: string | null
  Imei?: string | null
  IsActive?: boolean
}

/** Device as the backend returns it. `TerminalName` and `BranchName` are the names shown in the list. */
export interface DeviceData {
  Id: number
  TenantId: number
  TerminalId: number
  Code: string
  DeviceName?: string | null
  SerialNumber?: string | null
  IsActive: boolean
  CreatedAt: string
  CreatedBy: string
  UpdatedAt?: string | null
  UpdatedBy?: string | null
  TenantName?: string | null
  TerminalName?: string | null
  BranchName?: string | null
}

/** `POST /tenants/{tenantId}/devices`: a terminal holds at most one device; the serial is unique in the whole system. */
export interface CreateDevicePayload {
  TerminalId: number
  Code: string
  DeviceName?: string | null
  SerialNumber: string
}

/** `PUT /tenants/{tenantId}/devices/{id}`: every field optional (a partial update is valid). */
export interface UpdateDevicePayload {
  TerminalId?: number
  Code?: string
  DeviceName?: string | null
  SerialNumber?: string
  IsActive?: boolean
}

/** One rejected row of a CSV import (`Fila` is the 1-based file row, header included). */
export interface BulkImportError {
  Fila: number
  Campo: string
  Mensaje: string
}

/** One temporary credential generated by a UserApp import (SECRET: never printed, logged or thrown). */
export interface BulkImportCredential {
  UserName: string
  PasswordTemporal: string
}

/** Result of `POST .../import-csv`. `CredencialesGeneradas` is only filled by the UserApp import. */
export interface BulkImportResultData {
  Total: number
  Exitosos: number
  Fallidos: number
  Errores: BulkImportError[]
  CredencialesGeneradas?: BulkImportCredential[]
}

