/**
 * ADM tenant administrators: the lifecycle of ONE mailed account (ADM-001, 003, 008, 009, 005,
 * 006, 007, 012, 010), in this order and in serial mode.
 *
 * Mail budget (Mailtrap sandbox, shared with the other mailed specs): ADM-001 sends the welcome
 * mail (1 mail); ADM-008 sends the resent mail (the 2nd, tagged `@resend` so a first run can leave
 * it out with `--grep-invert @resend`). Everything else is mail free. The whole describe carries
 * `@mailbox`, so broad runs exclude it with `--grep-invert @mailbox`.
 *
 * Order, because the account must be PENDING for ADM-008 and ADM-009 and ACTIVE for the rest:
 *   001 create (pending) -> 003 duplicate e-mail -> 008 resend (new token) -> 009 activation shown
 *   in the open tab (the activation is triggered through the API there) -> 005 edit -> 006 weak
 *   password -> 007 lock and unlock -> 012 inactive login -> 010 the only admin cannot be deleted.
 * The account is the only admin of its generated tenant, which is what ADM-010 needs.
 *
 * The api describes start from an empty cookie jar (each ATC opens its own crypto session and one
 * positive Administrator login); the ui describe keeps the saved Administrator browser session.
 * Wrong passwords go only to the GENERATED account. Trace is off: tokens and cookies are live.
 * Tenants, accounts and mails are generated by `TenantAdminAccountSteps` and always deleted in
 * `afterAll`. No ATC calls another ATC: the chain is handed over here, through the Steps.
 */

import type { GeneratedTenant } from '@steps/TenantAdminAccountSteps';

import { TenantAdminAccountSteps } from '@steps/TenantAdminAccountSteps';
import { test } from '@TestFixture';

test.use({ trace: 'off' });

test.describe('ADM: tenant administrator lifecycle', { tag: ['@mailbox'] }, () => {
  test.describe.configure({ mode: 'serial' });

  const steps = new TenantAdminAccountSteps();
  const secrets = steps.secrets();
  let tenant: GeneratedTenant;
  let secondTenant: GeneratedTenant;
  let admin: { id: number, username: string };

  /** Where the shared account lives (valid once ADM-001 adopted it). */
  const account = () => ({ tenantId: tenant.id, tenantAdminId: admin.id, userName: admin.username });

  test.beforeAll(async () => {
    test.setTimeout(120000);
    try {
      tenant = await steps.prepareTenant();
      secondTenant = await steps.prepareSecondTenant();
    }
    catch (error) {
      await steps.cleanup().catch(() => undefined);
      throw error;
    }
  });

  test.afterAll(async () => {
    test.setTimeout(120000);
    await steps.cleanup();
  });

  test.describe('create, duplicate and resend (account pending)', () => {
    test.use({ storageState: { cookies: [], origins: [] } });

    test('ADM-001: should create a tenant administrator with a corporate e-mail and send the welcome mail', async ({ api }) => {
      test.setTimeout(180000);
      await api.tenantAdmins.createTenantAdminWithCorporateEmail({
        tenantId: tenant.id,
        adopt: (created) => {
          admin = created;
          steps.adoptTenantAdmin(created);
        },
        waitForMailSlot: async () => steps.waitForMailSlot(),
        markMailSent: () => steps.markMailSent(),
        confirmWelcomeMail: async () => steps.confirmWelcomeMail(),
      });
    });

    test('ADM-003: should reject a duplicate e-mail in the same tenant, in another tenant and in upper case', async ({ api }) => {
      test.setTimeout(120000);
      await api.tenantAdmins.rejectDuplicateEmail({
        tenantId: tenant.id,
        secondTenantId: secondTenant.id,
        userName: admin.username,
        trackCreated: account => steps.trackTenantAdmin(account),
      });
    });

    test('ADM-008: should resend the activation mail with a new token and refuse the old one', { tag: ['@resend'] }, async ({ api }) => {
      test.setTimeout(180000);
      await api.tenantAdmins.resendActivationWithNewToken({
        userName: admin.username,
        waitForMailSlot: async () => steps.waitForMailSlot(),
        markMailSent: () => steps.markMailSent(),
        confirmResentMail: async () => steps.confirmResentMail(),
        readFirstActivationToken: secrets.readFirstActivationToken,
      });
    });
  });

  test.describe('activation shown in the open tab (account pending, then active)', () => {
    test('ADM-009: should show the activation in the Administradores tab without reloading', async ({ ui }) => {
      test.setTimeout(120000);
      await ui.tenantAdmins.showActivationWithoutReload({
        tenantId: tenant.id,
        fullName: steps.adoptedAdminFullName,
        activate: async () => steps.activateAccount(),
      });
    });
  });

  test.describe('edit, lock, inactive and last admin (account active)', () => {
    test.use({ storageState: { cookies: [], origins: [] } });

    test('ADM-005: should edit name, position, password and status of the administrator', async ({ api }) => {
      test.setTimeout(120000);
      await api.tenantAdmins.editNamePositionPasswordAndStatus({
        ...account(),
        rememberPassword: newPassword => steps.adoptPassword(newPassword),
      });
    });

    test('ADM-006: should reject a weak password on edit and keep the current one', async ({ api }) => {
      test.setTimeout(120000);
      await api.tenantAdmins.rejectWeakPasswordOnEdit({
        ...account(),
        readPassword: secrets.readPassword,
      });
    });

    test('ADM-007: should let a locked administrator sign in again after the unlock', async ({ api }) => {
      // Flow plus the ~31 s address-limiter wait in `finally` exceed the 60 s global timeout
      test.setTimeout(180000);
      await api.tenantAdmins.unlockLockedTenantAdmin({
        ...account(),
        readPassword: secrets.readPassword,
      });
    });

    test('ADM-012: should reject the sign-in of an inactive administrator', async ({ api }) => {
      // Flow plus the ~31 s address-limiter wait in `finally` exceed the 60 s global timeout
      test.setTimeout(180000);
      await api.tenantAdmins.rejectInactiveTenantAdminLogin({
        ...account(),
        readPassword: secrets.readPassword,
      });
    });

    test('ADM-010: should not delete the only administrator of a tenant', async ({ api }) => {
      test.setTimeout(120000);
      await api.tenantAdmins.rejectDeleteOfOnlyAdmin({ tenantId: tenant.id, tenantAdminId: admin.id });
    });
  });
});
